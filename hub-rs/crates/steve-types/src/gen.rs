//! Explicit, test-only export inventory: default tests read; blessing is the only writer.

use crate::*;
use std::{collections::BTreeMap, fs, path::Path};
use ts_rs::{Config, TS};

const REWRITE: &str =
    "STEVE_TS_BLESS=1 cargo test --manifest-path hub-rs/Cargo.toml -p steve-types gen";
const HEADER: &str = "// generated by ts-rs from hub-rs/crates/steve-types — do not edit\n";

#[test]
fn bindings_match() {
    // JSON numbers are parsed as JS numbers. Do not inherit machine-specific ts-rs env settings.
    let config = Config::new().with_large_int("number");
    let mut files = BTreeMap::new();
    macro_rules! export {
        ($($ty:ty),+ $(,)?) => { $(
            files.insert(
                format!("{}.ts", <$ty>::ident(&config)),
                format!("{HEADER}{}", <$ty>::export_to_string(&config).expect("TS export")),
            );
        )+ };
    }
    export!(
        WorkspaceId,
        UserId,
        ItemId,
        SessionId,
        DecisionId,
        MessageId,
        ThreadRunId,
        BotId,
        ProjectId,
        TagId,
        DeviceId,
        NodeId,
        ClientId,
        PartyId,
        MemoryId,
        ChangesetId,
        AccountId,
        ConnectionId,
        VaultItemId,
        SignalId,
        FlowId,
        FlowRunId,
        SpaceId,
        ChanMessageId,
        PersonaId,
        CalendarId,
        YoloActionId,
        KbSourceId,
        KbDocId,
        MailThreadId,
        NotificationId,
        Epoch,
        Rev,
        Millis,
        Seq,
        RawJson,
        Code,
        Retry,
        Param,
        Params,
        Reason,
        Error,
        HttpErrorBody,
        Envelope<DomainEvent>,
        Scope,
        BusEvent,
        DomainEvent,
        LiveEvent,
        StreamControl,
        DurableFact,
        MailDelivery,
        PrSupplement,
        AlarmFired,
        AlarmLine,
        WorkEvent,
        ConfigEvent,
        DevicesEvent,
        ChannelsEvent,
        PeopleEvent,
        VaultEvent,
        AutomationEvent,
        AutonomyEvent,
        StatsEvent,
        KnowledgeEvent,
        IntegrationsEvent,
        WorkLiveEvent,
    );
    let index = files
        .keys()
        .map(|file| {
            let name = file.strip_suffix(".ts").unwrap();
            format!("export type {{ {name} }} from \"./{name}\";\n")
        })
        .collect::<String>();
    files.insert("index.ts".into(), format!("{HEADER}{index}"));
    let dir = Path::new(env!("CARGO_MANIFEST_DIR")).join("../../../web/src/gen");
    if std::env::var("STEVE_TS_BLESS").as_deref() == Ok("1") {
        fs::create_dir_all(&dir).unwrap();
        for entry in fs::read_dir(&dir).unwrap() {
            let entry = entry.unwrap();
            if !files.contains_key(&entry.file_name().to_string_lossy().into_owned()) {
                // Only generated files are ours to remove; unexpected directories require review.
                fs::remove_file(entry.path()).unwrap();
            }
        }
        for (name, body) in &files {
            fs::write(dir.join(name), body).unwrap();
        }
    }
    let actual: BTreeMap<_, _> = fs::read_dir(&dir)
        .unwrap_or_else(|e| panic!("{}: {e}; rewrite with `{REWRITE}`", dir.display()))
        .map(|e| {
            let e = e.unwrap();
            let name = e.file_name().into_string().unwrap();
            let body = fs::read_to_string(e.path()).unwrap();
            (name, body)
        })
        .collect();
    let differences: Vec<_> = files
        .keys()
        .chain(actual.keys())
        .filter(|name| files.get(*name) != actual.get(*name))
        .collect();
    assert!(
        differences.is_empty(),
        "generated bindings missing, extra or stale: {differences:?}; rewrite with `{REWRITE}`"
    );
}
