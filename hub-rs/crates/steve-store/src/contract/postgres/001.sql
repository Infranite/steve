-- PostgreSQL's contract test baseline. SQLite's deployed migrations stay in migrations/.
CREATE TABLE workspaces (
    id TEXT PRIMARY KEY,
    name TEXT NOT NULL,
    created BIGINT NOT NULL
);
CREATE TABLE settings (
    workspace_id TEXT NOT NULL REFERENCES workspaces(id),
    key TEXT NOT NULL,
    value TEXT NOT NULL,
    updated BIGINT NOT NULL,
    PRIMARY KEY (workspace_id, key)
);
CREATE TABLE sessions (
    id TEXT PRIMARY KEY,
    workspace_id TEXT NOT NULL REFERENCES workspaces(id),
    first_tool_at BIGINT
);
CREATE TABLE events (
    seq BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id TEXT NOT NULL REFERENCES sessions(id) ON DELETE CASCADE,
    ts BIGINT NOT NULL,
    kind TEXT NOT NULL,
    data TEXT NOT NULL,
    format TEXT NOT NULL,
    source_node TEXT,
    source_stream TEXT,
    source_epoch TEXT,
    source_seq BIGINT,
    source_attempt TEXT
);
CREATE UNIQUE INDEX events_source ON events (source_node, source_stream, source_epoch, source_seq)
    WHERE source_node IS NOT NULL;
CREATE INDEX events_session_seq ON events (session_id, seq);
CREATE TABLE event_payloads (
    session_id TEXT NOT NULL REFERENCES sessions(id) ON DELETE CASCADE,
    hash TEXT NOT NULL,
    data TEXT NOT NULL,
    PRIMARY KEY (session_id, hash)
);
CREATE TABLE event_payload_refs (
    event_seq BIGINT NOT NULL REFERENCES events(seq) ON DELETE CASCADE,
    path TEXT NOT NULL,
    session_id TEXT NOT NULL,
    hash TEXT NOT NULL,
    PRIMARY KEY (event_seq, path),
    FOREIGN KEY (session_id, hash) REFERENCES event_payloads(session_id, hash)
);
CREATE TABLE node_streams (
    node_id TEXT NOT NULL,
    stream TEXT NOT NULL,
    epoch TEXT NOT NULL,
    applied BIGINT NOT NULL DEFAULT 0,
    session_id TEXT REFERENCES sessions(id),
    fault TEXT,
    fault_event TEXT,
    fault_reason TEXT,
    PRIMARY KEY (node_id, stream, epoch)
);
CREATE TABLE runtime_attempts (
    attempt_id TEXT PRIMARY KEY,
    state TEXT NOT NULL,
    active_at BIGINT
);
CREATE TABLE runtime_attempt_facts (
    attempt_id TEXT PRIMARY KEY REFERENCES runtime_attempts(attempt_id) ON DELETE CASCADE,
    tools TEXT NOT NULL,
    permissions BIGINT NOT NULL,
    model TEXT,
    cost DOUBLE PRECISION
);
CREATE TABLE runtime_cost_marks (
    node_id TEXT NOT NULL,
    stream TEXT NOT NULL,
    epoch TEXT NOT NULL,
    meter_epoch TEXT NOT NULL,
    cost DOUBLE PRECISION NOT NULL,
    PRIMARY KEY (node_id, stream, epoch, meter_epoch)
);
CREATE TABLE runtime_sessions (
    session_id TEXT PRIMARY KEY REFERENCES sessions(id),
    node_id TEXT NOT NULL,
    node_revision TEXT,
    node_resume TEXT,
    node_views TEXT NOT NULL DEFAULT '[]'
);
CREATE TABLE decisions (
    id TEXT PRIMARY KEY,
    workspace_id TEXT NOT NULL REFERENCES workspaces(id),
    kind TEXT NOT NULL,
    subject_type TEXT NOT NULL,
    subject_id TEXT NOT NULL,
    item_id TEXT,
    session_id TEXT REFERENCES sessions(id),
    question TEXT NOT NULL,
    draft TEXT NOT NULL,
    options TEXT NOT NULL,
    status TEXT NOT NULL,
    result TEXT,
    requested_by TEXT NOT NULL,
    created BIGINT NOT NULL,
    resolved BIGINT,
    undo TEXT,
    revision BIGINT NOT NULL DEFAULT 1,
    source_revision TEXT,
    question_template TEXT CHECK (question_template IS NULL OR question = ''),
    UNIQUE (workspace_id, subject_type, subject_id, kind, source_revision)
);
CREATE TABLE decision_choice_receipts (
    decision_id TEXT NOT NULL REFERENCES decisions(id) ON DELETE CASCADE,
    revision BIGINT NOT NULL,
    actor TEXT NOT NULL,
    action TEXT NOT NULL,
    answer TEXT NOT NULL,
    recorded_at BIGINT NOT NULL,
    PRIMARY KEY (decision_id, revision)
);

CREATE TABLE chan_write_blocks (
    connection_id TEXT NOT NULL,
    space_id TEXT NOT NULL,
    workspace_id TEXT NOT NULL REFERENCES workspaces(id),
    reason TEXT NOT NULL,
    blocked_at BIGINT NOT NULL,
    until BIGINT NOT NULL,
    noticed_at BIGINT,
    PRIMARY KEY (connection_id, space_id)
);
CREATE TABLE audit (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workspace_id TEXT NOT NULL REFERENCES workspaces(id),
    ts BIGINT NOT NULL,
    actor TEXT NOT NULL,
    action TEXT NOT NULL,
    target TEXT NOT NULL,
    detail TEXT NOT NULL
);
CREATE TABLE revisions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workspace_id TEXT NOT NULL REFERENCES workspaces(id),
    object_type TEXT NOT NULL,
    object_id TEXT NOT NULL,
    version BIGINT NOT NULL,
    patch TEXT NOT NULL,
    author TEXT NOT NULL,
    created BIGINT NOT NULL
);

CREATE TABLE connections (
    id TEXT PRIMARY KEY,
    workspace_id TEXT NOT NULL REFERENCES workspaces(id)
);
CREATE TABLE gh_repos (
    id TEXT PRIMARY KEY,
    workspace_id TEXT NOT NULL REFERENCES workspaces(id),
    ingest TEXT NOT NULL,
    enabled BIGINT NOT NULL DEFAULT 1,
    last_delivery BIGINT,
    poll_state TEXT NOT NULL DEFAULT '{}'
);

CREATE TABLE source_settings (
    connection_id TEXT PRIMARY KEY REFERENCES connections(id), workspace_id TEXT NOT NULL,
    paused BIGINT NOT NULL DEFAULT 0,
    triage_bot TEXT,
    types TEXT NOT NULL DEFAULT '{}',
    scopes TEXT NOT NULL DEFAULT '[]',
    cursor TEXT,
    revision BIGINT NOT NULL DEFAULT 1, updated BIGINT NOT NULL
);

CREATE TABLE kb_marks (
    workspace_id TEXT NOT NULL, name TEXT NOT NULL,
    value TEXT NOT NULL, updated BIGINT NOT NULL, PRIMARY KEY (workspace_id, name)
);

CREATE TABLE project_proposals (
    id TEXT PRIMARY KEY,
    workspace_id TEXT NOT NULL REFERENCES workspaces(id),
    project_id TEXT NOT NULL,
    kind TEXT NOT NULL DEFAULT 'agents_md',
    text TEXT NOT NULL,
    reason TEXT NOT NULL DEFAULT '',
    evidence TEXT NOT NULL DEFAULT '',
    origin_kind TEXT NOT NULL DEFAULT '',
    origin_id TEXT,
    origin_label TEXT NOT NULL DEFAULT '',
    status TEXT NOT NULL DEFAULT 'pending',
    decision_id TEXT,
    writer TEXT NOT NULL DEFAULT 'steve',
    created_by TEXT NOT NULL DEFAULT '',
    created BIGINT NOT NULL,
    updated BIGINT NOT NULL
);

CREATE TABLE mail_account_settings (
    connection_id TEXT PRIMARY KEY REFERENCES connections(id), workspace_id TEXT NOT NULL,
    signature TEXT NOT NULL DEFAULT '',
    duty TEXT NOT NULL DEFAULT '',
    send_delay_s BIGINT NOT NULL DEFAULT 10,
    archive_on_done BIGINT NOT NULL DEFAULT 0,
    sync_days BIGINT NOT NULL DEFAULT 30,
    append_sent TEXT NOT NULL DEFAULT 'auto',
    revision BIGINT NOT NULL DEFAULT 1, updated BIGINT NOT NULL
);

CREATE TABLE price_sync (
    source TEXT PRIMARY KEY,
    synced BIGINT, tried BIGINT, error TEXT,
    etag TEXT,
    models BIGINT NOT NULL DEFAULT 0
);

CREATE TABLE nodes (
    node_id TEXT PRIMARY KEY,
    owner TEXT NOT NULL,
    name TEXT NOT NULL,
    pubkey BYTEA NOT NULL CHECK(length(pubkey)=32),
    fingerprint TEXT NOT NULL UNIQUE,
    state TEXT NOT NULL CHECK(state IN ('pending','active','paused','revoked')),
    generation BIGINT NOT NULL DEFAULT 0,
    incarnation BIGINT,
    local BIGINT NOT NULL DEFAULT 0 CHECK(local IN (0,1)),
    capabilities TEXT,
    created BIGINT NOT NULL,
    last_seen BIGINT,
    revoked_at BIGINT,
    revoked_by TEXT
);

CREATE TABLE cal_calendars (
    id TEXT PRIMARY KEY,
    workspace_id TEXT NOT NULL,
    connection_id TEXT NOT NULL REFERENCES connections(id) ON DELETE CASCADE,
    owner_user TEXT NOT NULL,
    ext_id TEXT NOT NULL,
    name TEXT NOT NULL,
    color TEXT,
    kind TEXT NOT NULL DEFAULT 'primary',
    role TEXT NOT NULL DEFAULT 'reader',
    share TEXT NOT NULL DEFAULT 'private',
    party_id TEXT,
    party_set BIGINT NOT NULL DEFAULT 0,
    detail TEXT NOT NULL DEFAULT 'full',
    enabled BIGINT NOT NULL DEFAULT 1,
    tz TEXT,
    sync_cursor TEXT,
    synced_at BIGINT,
    full_at BIGINT,
    sync_state TEXT NOT NULL DEFAULT 'new',
    sync_error TEXT,
    gone BIGINT NOT NULL DEFAULT 0,
    created BIGINT NOT NULL,
    updated BIGINT NOT NULL,
    UNIQUE (connection_id, ext_id)
);

CREATE TABLE briefings (
    id TEXT PRIMARY KEY,
    workspace_id TEXT NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
    user_id TEXT NOT NULL,
    day TEXT NOT NULL,
    schedule_id TEXT,
    event_id TEXT NOT NULL,
    material TEXT NOT NULL,
    pushed BIGINT NOT NULL CHECK(pushed IN (0,1)),
    created BIGINT NOT NULL,
    UNIQUE(workspace_id, user_id, day)
);
