//! SG43: compact characterization of command text; nothing in this table is executed.
use serde_json::{Value, json};
use steve_core::yolo::{
    full_guard,
    guard::{self, Guard},
    judge::{Env, Facts, Subject, Tool},
    limits,
};
fn shown(g: Guard) -> Value {
    match g {
        Guard::Allow { option, checks } => json!({"allow":option,"checks":checks}),
        Guard::Ask(why) => json!({"ask":why}),
    }
}
