//! The hand-off from reply generation (C4) to the outbound path (C6, channels-personas.md §2.7,
//! §10): everything C4 wants said in a channel — generated replies, “收到，已记为 <编号>。”, the
//! `reply_as` / `send_to_space` flow actions — goes through one [`Outbound`]. C4 itself never sends.
//!
//! [`DraftOnly`] (the default) makes every message a pending draft (`chan_messages`
//! `direction=out, status=draft`) with its `approve` decision. C6's [`crate::outbound::Outbox`] is the
//! real one (authorization → disclosure check → redactor → send → basis → audit).

use async_trait::async_trait;
use steve_knowledge::Hit;

use crate::respond::{self, Plan};
use crate::spaces::Mode;
use crate::{ChannelResult, Channels};

/// Why something is said.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Purpose {
    /// A rule's `reply` / `draft` (§2.5), generated by C4.
    Reply,
    /// The acknowledgement of `create_item` (“收到，已记为 <编号>。”).
    Item,
    /// A handoff's “我请 <主人称呼> 来看。” (only when not muted).
    HandoffAck,
    /// A `reply_as` / `send_to_space` flow action.
    Flow,
    /// Your own trigger words (§2.7): Steve speaks as you.
    Trigger,
    /// Back to the source: “<编号> 已完成：…” in the thread an item came from (§2.7).
    Done,
    /// `steve_reply_source`: an agent's update to the chat its item came from (§6).
    Source,
}

/// What lets a message go out without a draft (§10: “授权（规则或决定）”). The outbound verifies it
/// against the store again right before the adapter is called; anything else becomes a draft.
#[derive(Debug, Clone, PartialEq, Eq, Default, serde::Serialize, serde::Deserialize)]
pub enum Auth {
    /// Nothing: a draft for your approval.
    #[default]
    None,
    /// A bot account's response rule that speaks (`reply`; `create_item`'s “收到，已记为…”;
    /// `handoff`'s “我请…来看。”) for the inbound message it answers.
    Rule {
        source: String,
        act: crate::rules::Act,
    },
    /// Your own trigger words in your own message (only on your own account).
    Trigger { source: String },
    /// A live `msg.send` grant of the flow.
    Grant { flow_id: String, run_id: String },
    /// The flow engine's approval for this run: `gate` = you approved exactly this step (its fixed
    /// text was on the card), else an `approve` node earlier on the path.
    Step {
        run_id: String,
        node_id: String,
        gate: bool,
    },
    /// You approved this message (a resolved `approve` `yes` or `fail` `retry` decision about it).
    Decision { id: String },
}

impl Auth {
    /// For the audit log.
    pub fn code(&self) -> &'static str {
        match self {
            Self::None => "none",
            Self::Rule { .. } => "rule",
            Self::Trigger { .. } => "trigger",
            Self::Grant { .. } => "grant",
            Self::Step { .. } => "step",
            Self::Decision { .. } => "decision",
        }
    }
}

/// Where a message goes and as whom.
#[derive(Debug, Clone, PartialEq)]
pub struct OutTarget {
    pub ws: String,
    pub connection_id: String,
    pub mode: Mode,
    pub space_id: String,
    pub space_name: String,
    /// The provider id of the message replied to (`None`: a new message in the space).
    pub reply_to: Option<String>,
    pub thread_key: Option<String>,
    /// A persona chosen explicitly (flow `persona_id`); `None` = the space's effective persona.
    /// Always `None` on your own accounts.
    pub persona_id: Option<String>,
    /// The inbound `cm_…` this answers, if any.
    pub source_message_id: Option<String>,
}

impl OutTarget {
    /// A reply to the plan's message, in its thread.
    pub fn reply(plan: &Plan) -> Self {
        Self {
            ws: plan.ws.clone(),
            connection_id: plan.connection_id.clone(),
            mode: plan.mode,
            space_id: plan.space_id.clone(),
            space_name: plan.space_name.clone(),
            reply_to: Some(plan.external_id.clone()).filter(|e| !e.is_empty()),
            thread_key: plan.thread_key.clone(),
            persona_id: None,
            source_message_id: Some(plan.message_id.clone()),
        }
    }
}

/// What the generator decided to do with a message (compose.rs `OUTPUT`). Only `Reply` is said in
/// the space; `AskOwner` is a question to you in Steve's conversation, `Skip` nothing to say.
#[derive(Debug, Clone, PartialEq, Eq, Default)]
pub enum Outcome {
    #[default]
    Reply,
    /// Needs your judgment: the text is the question to you, never said in the space.
    AskOwner,
    /// Small talk, or nothing a reply would add: the text is the reason.
    Skip,
    /// The model needs more of the conversation first (the composer widens the history once and
    /// asks again; never returned by `Composer::generate`).
    NeedContext,
}

impl Outcome {
    pub fn code(&self) -> &'static str {
        match self {
            Self::Reply => "reply",
            Self::AskOwner => "ask_owner",
            Self::Skip => "skip",
            Self::NeedContext => "need_context",
        }
    }
}

/// What the generator said about its text (empty for fixed texts).
#[derive(Debug, Clone, PartialEq, Default)]
pub struct Generation {
    /// Reply, ask you, or say nothing; only a reply goes out.
    pub outcome: Outcome,
    /// The model asked for approval (an outward promise, money, deleting something).
    pub needs_approval: bool,
    pub why: String,
    /// The model that answered.
    pub model: String,
    /// Layer 7: the knowledge the reply was written with (C5 checks against it and writes the basis).
    pub hits: Vec<Hit>,
    /// Layer 6: the contact card and memory ids shown (for the basis).
    pub anchors: Vec<String>,
}

/// One message to say.
#[derive(Debug, Clone, PartialEq)]
pub struct OutRequest {
    pub target: OutTarget,
    pub text: String,
    pub purpose: Purpose,
    /// Must not go out without your approval: a `draft` act, an `approve` flow node, your own
    /// account, or the model's `needs_approval`. C6 may still draft when this is `false`.
    pub approve: bool,
    /// Present when C4 generated the text.
    pub generation: Option<Generation>,
    /// What lets it go out directly (C6 checks it again before sending).
    pub auth: Auth,
}

/// What became of a message.
#[derive(Debug, Clone, PartialEq)]
pub enum Delivered {
    /// Waiting for your approval.
    Drafted {
        message_id: String,
        decision_id: String,
    },
    /// Sent (only C6 does this).
    Sent { message_id: String },
    /// A secret value was in it: not sent, not drafted (a `fail` decision tells you).
    Blocked {
        message_id: String,
        decision_id: String,
    },
    /// The provider refused it; a `fail` decision (retry / discard) is open.
    Failed {
        message_id: String,
        decision_id: String,
    },
    /// On its way, not confirmed: waiting for its connection (paused), or sent without an answer
    /// (`unknown`; the queue sends it again while the provider drops repeats, else asks you).
    Queued { message_id: String },
    /// Not said at all (a handoff acknowledgement while drafts are all there is).
    Skipped,
}

impl Delivered {
    pub fn message_id(&self) -> Option<&str> {
        match self {
            Self::Drafted { message_id, .. }
            | Self::Sent { message_id }
            | Self::Blocked { message_id, .. }
            | Self::Failed { message_id, .. }
            | Self::Queued { message_id } => Some(message_id),
            Self::Skipped => None,
        }
    }

    pub fn decision_id(&self) -> Option<&str> {
        match self {
            Self::Drafted { decision_id, .. }
            | Self::Blocked { decision_id, .. }
            | Self::Failed { decision_id, .. } => Some(decision_id),
            _ => None,
        }
    }
}

/// The outbound path (C6 implements it). Must authorize, check disclosure and audit before any
/// adapter `send(`; C4 never calls an adapter itself.
#[async_trait]
pub trait Outbound: Send + Sync {
    async fn deliver(&self, ch: &Channels, req: &OutRequest) -> ChannelResult<Delivered>;
}

/// The outbound until C6: drafts everything with an `approve` decision; skips handoff
/// acknowledgements (the handoff's own decision already reaches you).
#[derive(Debug, Default, Clone, Copy)]
pub struct DraftOnly;

#[async_trait]
impl Outbound for DraftOnly {
    async fn deliver(&self, ch: &Channels, req: &OutRequest) -> ChannelResult<Delivered> {
        if req.purpose == Purpose::HandoffAck {
            return Ok(Delivered::Skipped);
        }
        let now = ch.now();
        let (message_id, decision_id) = ch
            .store()
            .transaction(|tx| respond::open_draft_to(tx, &req.target, &req.text, now))?;
        Ok(Delivered::Drafted {
            message_id,
            decision_id,
        })
    }
}
