//! The hand-off from reply generation (C4) to the outbound path (C6):
//! everything C4 wants said in a channel — generated replies, “收到，已记为 <编号>。”, the
//! `reply_as` / `send_to_space` flow actions — goes through one [`Outbound`]. C4 itself never sends.
//!
//! [`DraftOnly`] (the default) makes every message a pending draft (`chan_messages`
//! `direction=out, status=draft`) with its `approve` decision. C6's [`crate::outbound::Outbox`] is the
//! real one (authorization → disclosure check → send → basis → audit).

use async_trait::async_trait;
use steve_knowledge::Hit;

use crate::respond::{self, Plan};
use crate::spaces::Mode;
use crate::{ChannelResult, Channels};

/// Why something is said.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Purpose {
    /// A rule's `reply` / `draft`, generated by C4.
    Reply,
    /// The acknowledgement of `create_item` (“收到，已记为 <编号>。”).
    Item,
    /// A handoff's “我请 <主人称呼> 来看。” (only when not muted).
    HandoffAck,
    /// A `reply_as` / `send_to_space` flow action.
    Flow,
    /// Your own trigger words: Steve speaks as you.
    Trigger,
    /// Back to the source: “<编号> 已完成：…” in the thread an item came from.
    Done,
    /// `steve_reply_source`: an agent's update to the chat its item came from.
    Source,
}

/// What lets a message go out without a draft (“授权（规则或决定）”). The outbound verifies it
/// against the store again right before the adapter is called; anything else becomes a draft.
#[derive(Debug, Clone, PartialEq, Eq, Default, serde::Serialize, serde::Deserialize)]
pub enum Auth {
    /// Nothing: a draft for your approval.
    #[default]
    None,
    /// A live member explicitly requested a bot send, bound to a durable output intent.
    /// Never valid on personal accounts or on legacy messages without that intent.
    Requester { user: String },
    /// A bot account's response rule that speaks (`reply`; `create_item`'s “收到，已记为…”;
    /// `handoff`'s “我请…来看。”) for the inbound message it answers.
    Rule {
        source: String,
        act: crate::rules::Act,
    },
    /// Your own trigger words in your own message (only on your own account).
    Trigger { source: String },
    /// A live `msg.send` grant of the flow, for the flow version the run is running (a grant is
    /// bound to one version: an edit of the flow ends it).
    Grant {
        flow_id: String,
        run_id: String,
        #[serde(default)]
        flow_version: i64,
    },
    /// The flow engine's approval for this run: `gate` = you approved exactly this step (its fixed
    /// text was on the card), else an `approve` node earlier on the path.
    Step {
        run_id: String,
        node_id: String,
        gate: bool,
    },
    /// You approved this message (a resolved `approve` `yes` or `fail` `retry` decision about it).
    Decision { id: String },
}

impl Auth {
    /// For the audit log.
    pub fn code(&self) -> &'static str {
        match self {
            Self::None => "none",
            Self::Requester { .. } => "requester",
            Self::Rule { .. } => "rule",
            Self::Trigger { .. } => "trigger",
            Self::Grant { .. } => "grant",
            Self::Step { .. } => "step",
            Self::Decision { .. } => "decision",
        }
    }
}

/// Where a message goes and as whom.
#[derive(Debug, Clone, PartialEq)]
pub struct OutTarget {
    pub ws: String,
    pub connection_id: String,
    pub mode: Mode,
    pub space_id: String,
    pub space_name: String,
    /// The provider id of the message replied to (`None`: a new message in the space).
    pub reply_to: Option<String>,
    pub thread_key: Option<String>,
    /// A persona chosen explicitly (flow `persona_id`); `None` = the space's effective persona.
    /// Always `None` on your own accounts.
    pub persona_id: Option<String>,
    /// The inbound `cm_…` this answers, if any.
    pub source_message_id: Option<String>,
}

impl OutTarget {
    /// A reply to the plan's message, in its thread.
    pub fn reply(plan: &Plan) -> Self {
        Self {
            ws: plan.ws.clone(),
            connection_id: plan.connection_id.clone(),
            mode: plan.mode,
            space_id: plan.space_id.clone(),
            space_name: plan.space_name.clone(),
            reply_to: Some(plan.external_id.clone()).filter(|e| !e.is_empty()),
            thread_key: plan.thread_key.clone(),
            persona_id: None,
            source_message_id: Some(plan.message_id.clone()),
        }
    }
}

/// The fixed sentences Steve writes itself that may end up next to a reply, `{}` where a template
/// takes a value: the composer's question when it still cannot place a message, its reason for not
/// answering, the options added to a question, the item and hand-off acknowledgements, the failure
/// note. None is ever the composer's reply to a message, so a reply drafted as you that contains one
/// was not written by the composer for that message ([`system_text_in`]). The offline reply eval
/// (`examples/reply_eval`) counts such drafts as leaks, together with the router's own sentences
/// (`steve_core::thread::research::QUEUE_FULL`), which this crate cannot name.
pub const SYSTEM_TEXTS: &[&str] = &[
    crate::compose::UNCLEAR,
    crate::conversations::NO_REPLY,
    crate::conversations::OPTIONS_HEAD,
    crate::conversations::FAILURE_NOTE,
    crate::replies::ITEM_ACK,
    crate::replies::PROPOSE_ACK,
    crate::rules::HANDOFF_ACK,
];

/// A value in a [`SYSTEM_TEXTS`] template, in characters at most (a name, an item id).
const TEMPLATE_VALUE_MAX: usize = 40;

/// The first of `templates` that `text` contains: a fixed sentence as it is, a template with any
/// value of up to [`TEMPLATE_VALUE_MAX`] characters (not across lines) where it has `{}`.
pub fn system_text_in<'a>(text: &str, templates: &[&'a str]) -> Option<&'a str> {
    templates
        .iter()
        .copied()
        .find(|t| matches_template(text, t))
}

fn matches_template(text: &str, template: &str) -> bool {
    let mut parts = template.split("{}");
    let first = parts.next().unwrap_or_default();
    let rest: Vec<&str> = parts.collect();
    if rest.is_empty() {
        return !first.is_empty() && text.contains(first);
    }
    text.match_indices(first)
        .any(|(at, _)| follows(&text[at + first.len()..], &rest))
}

/// `parts` in order at the start of `s`, each after a value of at most [`TEMPLATE_VALUE_MAX`]
/// characters on one line.
fn follows(s: &str, parts: &[&str]) -> bool {
    let Some((p, more)) = parts.split_first() else {
        return true;
    };
    s.match_indices(p).any(|(i, _)| {
        let value = &s[..i];
        !value.contains('\n')
            && value.chars().count() <= TEMPLATE_VALUE_MAX
            && follows(&s[i + p.len()..], more)
    })
}

/// What the generator decided to do with a message (compose.rs `OUTPUT`). Only `Reply` is said in
/// the space; `AskOwner` is a question to you in Steve's conversation, `Skip` nothing to say.
/// Stored as its [`Outcome::code`].
#[derive(Debug, Clone, PartialEq, Eq, Default, serde::Serialize, serde::Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum Outcome {
    #[default]
    Reply,
    /// Needs your judgment: the text is the question to you, never said in the space.
    AskOwner,
    /// Small talk, or nothing a reply would add: the text is the reason.
    Skip,
    /// The model needs more of the conversation first (the composer widens the history once and
    /// asks again; never returned by `Composer::generate`).
    NeedContext,
}

impl Outcome {
    pub fn code(&self) -> &'static str {
        match self {
            Self::Reply => "reply",
            Self::AskOwner => "ask_owner",
            Self::Skip => "skip",
            Self::NeedContext => "need_context",
        }
    }
}

/// What the generator said about its text (empty for fixed texts).
#[derive(Debug, Clone, PartialEq, Default, serde::Serialize, serde::Deserialize)]
#[serde(default)]
pub struct Generation {
    /// Reply, ask you, or say nothing; only a reply goes out.
    pub outcome: Outcome,
    /// The model asked for approval (an outward promise, money, deleting something).
    pub needs_approval: bool,
    pub why: String,
    /// The model that answered.
    pub model: String,
    /// Layer 7: the knowledge the reply was written with (C5 checks against it and writes the basis).
    pub hits: Vec<Hit>,
    /// Layer 6: the contact card and memory ids shown (for the basis).
    pub anchors: Vec<String>,
    /// On your own account, what the checks of writing as you found in the first draft
    /// ([`crate::voice::Problem::code`]); the text is the second try's. Empty: passed at once.
    #[serde(skip_serializing_if = "Vec::is_empty")]
    pub revised: Vec<String>,
    /// The model's reason as a code ([`crate::decide::Reason`]): for a question to you, what it needs
    /// you for (`commitment`, `owner_fact`, `substantive`, …); for a skip, why not. Empty: none given.
    #[serde(skip_serializing_if = "String::is_empty")]
    pub reason: String,
    /// Whom the message answered is for, as the model read it: `owner` (you), `others` (someone
    /// else, the group). Empty: not said.
    #[serde(skip_serializing_if = "String::is_empty")]
    pub addressee: String,
    /// The reply would promise something for you (to look into it, to do it, a time, a result,
    /// money, deleting something): it waits for you and YOLO never sends it. Kept with the draft
    /// (`chan_messages.composed`).
    #[serde(skip_serializing_if = "std::ops::Not::not")]
    pub needs_commitment: bool,
    /// One sentence on who wants what, for the card ([`crate::decide::SUMMARY_MAX`]).
    #[serde(skip_serializing_if = "String::is_empty")]
    pub summary: String,
    /// With a question to you: the reply it would send if you agree, shown on the card as the
    /// candidate draft (“发这条草稿”). Empty: none.
    #[serde(skip_serializing_if = "String::is_empty")]
    pub draft: String,
    /// On your own account, what the composer was shown of how you talk (your samples, your edited
    /// and rejected drafts): inputs for the tone, never content. The disclosure check flags their
    /// content copied into the reply (`CheckCx::style_samples`); kept with the draft
    /// (`chan_messages.composed`) for the check that runs after it is written.
    #[serde(skip_serializing_if = "Vec::is_empty")]
    pub style_samples: Vec<String>,
}

/// One message to say.
#[derive(Debug, Clone, PartialEq)]
pub struct OutRequest {
    pub target: OutTarget,
    pub text: String,
    pub purpose: Purpose,
    /// Must not go out without your approval: a `draft` act, an `approve` flow node, your own
    /// account, or the model's `needs_approval`. C6 may still draft when this is `false`.
    pub approve: bool,
    /// Present when C4 generated the text.
    pub generation: Option<Generation>,
    /// What lets it go out directly (C6 checks it again before sending).
    pub auth: Auth,
    /// The deterministic id of the operation this message is (what it answers, which turn, why),
    /// for a caller that may ask again for the same message: a retry, a restart, a second delivery
    /// pass. The outbound message is stored under an id derived from it ([`operation_message_id`]),
    /// claimed by the insert that first finds it free; a request whose operation already has its
    /// message gets that message's state back ([`delivered_of`]) and is never created or sent
    /// again. The id is also the provider's dedupe key of every send of it. `None`: a new message
    /// each time.
    pub operation_id: Option<String>,
}

/// The `chan_messages` id of operation `op` in workspace `ws` ([`OutRequest::operation_id`]): the
/// same for every request of it, shaped like any other outbound id.
pub fn operation_message_id(ws: &str, op: &str) -> String {
    let h = steve_store::sha(&format!("{ws}\n{op}"));
    format!("cm_{}", &h[..16])
}

/// What became of stored outbound message `message_id`, from its `status` and open `decision`.
pub fn delivered_of(message_id: &str, status: &str, decision: Option<&str>) -> Delivered {
    let message_id = message_id.to_string();
    match (status, decision) {
        ("draft", Some(id)) => Delivered::Drafted {
            message_id,
            decision_id: id.into(),
        },
        ("failed", Some(id)) => Delivered::Failed {
            message_id,
            decision_id: id.into(),
        },
        // refused for good, after the one notice about it (`write_blocks`)
        ("failed", None) => Delivered::Blocked { message_id },
        ("sent" | "recalled", _) => Delivered::Sent { message_id },
        ("discarded", _) => Delivered::Skipped,
        // pending (claimed, or waiting for the queue) or unknown (may be out): never sent from here
        _ => Delivered::Queued { message_id },
    }
}

/// The state of operation `op`'s outbound message, when it has one ([`OutRequest::operation_id`]).
pub fn operation_delivered(
    c: &rusqlite::Connection,
    ws: &str,
    op: &str,
) -> ChannelResult<Option<Delivered>> {
    use rusqlite::OptionalExtension;
    let id = operation_message_id(ws, op);
    let row: Option<(String, Option<String>)> = c
        .query_row(
            "SELECT status, decision_id FROM chan_messages
              WHERE id = ? AND workspace_id = ? AND direction = 'out'",
            rusqlite::params![id, ws],
            |r| Ok((r.get(0)?, r.get(1)?)),
        )
        .optional()?;
    Ok(row.map(|(status, decision)| delivered_of(&id, &status, decision.as_deref())))
}

/// What became of a message.
#[derive(Debug, Clone, PartialEq)]
pub enum Delivered {
    /// Waiting for your approval.
    Drafted {
        message_id: String,
        decision_id: String,
    },
    /// Sent (only C6 does this).
    Sent { message_id: String },
    /// The provider refused it; a `fail` decision (retry / discard) is open.
    Failed {
        message_id: String,
        decision_id: String,
    },
    /// On its way, not confirmed: waiting for its connection (paused), or sent without an answer
    /// (`unknown`; the queue sends it again while the provider drops repeats, else asks you).
    Queued { message_id: String },
    /// Not sent: the connection, or this chat, refuses writes for now (read-only; ext_ws protocol
    /// §3.6). Kept as not sent without a card of its own: the one notice about it is already out
    /// ([`crate::write_blocks`]).
    Blocked { message_id: String },
    /// Not said at all (a handoff acknowledgement while drafts are all there is, an automatic reply
    /// where writes are refused).
    Skipped,
}

impl Delivered {
    pub fn message_id(&self) -> Option<&str> {
        match self {
            Self::Drafted { message_id, .. }
            | Self::Sent { message_id }
            | Self::Failed { message_id, .. }
            | Self::Queued { message_id }
            | Self::Blocked { message_id } => Some(message_id),
            Self::Skipped => None,
        }
    }

    pub fn decision_id(&self) -> Option<&str> {
        match self {
            Self::Drafted { decision_id, .. } | Self::Failed { decision_id, .. } => {
                Some(decision_id)
            }
            _ => None,
        }
    }
}

/// Why a message may not be said as you, on your own account (`None`: it may, as a draft or as its
/// authorization allows). Only what the composer wrote as its reply to a message speaks as you: a
/// [`Purpose::Reply`] or [`Purpose::Trigger`] needs the composer's [`Generation`] with
/// [`Outcome::Reply`]; fixed receipts ([`Purpose::Item`], [`Purpose::HandoffAck`], [`Purpose::Done`])
/// are never said as you (they name you in the third person and show item ids; the item and the
/// handoff reach you in Steve). A flow's `reply_as` / `send_to_space` ([`Purpose::Flow`]) and an
/// agent's or requester's update ([`Purpose::Source`]: also your trigger words' fixed notes, a
/// refusal or a failure, `[AI]`-marked) are texts somebody asked for explicitly; their caller and
/// authorization decide. Every [`Outbound`] checks this before anything else.
pub fn not_as_you(mode: Mode, req: &OutRequest) -> Option<&'static str> {
    if mode != Mode::Own {
        return None;
    }
    match req.purpose {
        Purpose::Item | Purpose::HandoffAck | Purpose::Done => Some(NOT_AS_YOU_RECEIPT),
        Purpose::Reply | Purpose::Trigger => match &req.generation {
            Some(g) if g.outcome == Outcome::Reply => None,
            _ => Some(NOT_AS_YOU_UNCOMPOSED),
        },
        Purpose::Flow | Purpose::Source => None,
    }
}

/// [`not_as_you`]: a fixed receipt.
pub const NOT_AS_YOU_RECEIPT: &str = "本人账号不发 Steve 的固定回执";
/// [`not_as_you`]: a text the composer did not write as its reply.
pub const NOT_AS_YOU_UNCOMPOSED: &str = "不是起草器写的回复，不以你本人的名义发";

/// On your own account a reply always waits for your approval. The answer to your trigger words
/// ([`Purpose::Trigger`]) goes out as their settings say (`[AI]`-marked, #225), unless the composer
/// says it needs your approval: the caller decides.
pub fn must_approve(mode: Mode, req: &OutRequest) -> bool {
    req.approve || (mode == Mode::Own && req.purpose == Purpose::Reply)
}

/// The outbound path (C6 implements it). Must authorize, check disclosure and audit before any
/// adapter `send(`; C4 never calls an adapter itself.
#[async_trait]
pub trait Outbound: Send + Sync {
    async fn deliver(&self, ch: &Channels, req: &OutRequest) -> ChannelResult<Delivered>;
}

/// The outbound until C6: drafts everything with an `approve` decision; skips handoff
/// acknowledgements (the handoff's own decision already reaches you).
#[derive(Debug, Default, Clone, Copy)]
pub struct DraftOnly;

#[async_trait]
impl Outbound for DraftOnly {
    async fn deliver(&self, ch: &Channels, req: &OutRequest) -> ChannelResult<Delivered> {
        if req.purpose == Purpose::HandoffAck {
            return Ok(Delivered::Skipped);
        }
        if let Some(why) = not_as_you(req.target.mode, req) {
            tracing::info!(space = req.target.space_id, "not drafted: {why}");
            return Ok(Delivered::Skipped);
        }
        let now = ch.now();
        let ws = &req.target.ws;
        ch.store().transaction(|tx| {
            // asked again for the same operation: its draft, not a second one
            if let Some(op) = &req.operation_id
                && let Some(d) = operation_delivered(tx, ws, op)?
            {
                return Ok(d);
            }
            let id = match &req.operation_id {
                Some(op) => operation_message_id(ws, op),
                None => steve_store::uid("cm"),
            };
            let (m, d) = respond::open_draft_as(tx, &req.target, &req.text, now, id)?;
            if let Some(g) = &req.generation {
                crate::decide::keep_composed(tx, &m, g)?;
            }
            Ok::<_, crate::ChannelError>(Delivered::Drafted {
                message_id: m,
                decision_id: d,
            })
        })
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn req(purpose: Purpose, outcome: Option<Outcome>) -> OutRequest {
        OutRequest {
            target: OutTarget {
                ws: "w".into(),
                connection_id: "c".into(),
                mode: Mode::Own,
                space_id: "s".into(),
                space_name: String::new(),
                reply_to: None,
                thread_key: None,
                persona_id: None,
                source_message_id: None,
            },
            text: "好".into(),
            purpose,
            approve: false,
            generation: outcome.map(|outcome| Generation {
                outcome,
                ..Default::default()
            }),
            auth: Auth::None,
            operation_id: None,
        }
    }

    #[test]
    fn only_the_composers_reply_speaks_as_you() {
        use Purpose::*;
        for p in [Reply, Trigger] {
            assert_eq!(not_as_you(Mode::Own, &req(p, Some(Outcome::Reply))), None);
            // a reply waits for you; your trigger words' answer goes as their settings say
            assert_eq!(
                must_approve(Mode::Own, &req(p, Some(Outcome::Reply))),
                p == Reply,
                "{p:?}"
            );
            for o in [
                None,
                Some(Outcome::AskOwner),
                Some(Outcome::Skip),
                Some(Outcome::NeedContext),
            ] {
                assert_eq!(
                    not_as_you(Mode::Own, &req(p, o.clone())),
                    Some(NOT_AS_YOU_UNCOMPOSED),
                    "{p:?} {o:?}"
                );
            }
        }
        for p in [Item, HandoffAck, Done] {
            assert_eq!(
                not_as_you(Mode::Own, &req(p, None)),
                Some(NOT_AS_YOU_RECEIPT)
            );
        }
        for p in [Flow, Source] {
            assert_eq!(not_as_you(Mode::Own, &req(p, None)), None, "{p:?}");
            assert!(
                !must_approve(Mode::Own, &req(p, None)),
                "{p:?}: the caller decides"
            );
        }
        // a bot speaks for itself
        for p in [Reply, Trigger, Item, HandoffAck, Done, Flow, Source] {
            assert_eq!(not_as_you(Mode::Bot, &req(p, None)), None);
            assert!(!must_approve(Mode::Bot, &req(p, None)));
        }
    }

    #[test]
    fn a_generation_reads_back_as_it_was_kept() {
        let g = Generation {
            outcome: Outcome::AskOwner,
            needs_approval: true,
            why: "要你定".into(),
            model: "m".into(),
            hits: Vec::new(),
            anchors: vec!["mem:1".into()],
            revised: vec!["opener".into()],
            reason: "commitment".into(),
            addressee: "owner".into(),
            needs_commitment: true,
            summary: "A 问周四能不能开会".into(),
            draft: "周四可以".into(),
            style_samples: vec!["稍等".into()],
        };
        let v = serde_json::to_value(&g).unwrap();
        assert_eq!(v["outcome"], "ask_owner");
        assert_eq!(serde_json::from_value::<Generation>(v).unwrap(), g);
        assert_eq!(
            serde_json::from_value::<Generation>(serde_json::json!({"outcome": "reply"})).unwrap(),
            Generation::default()
        );
    }
}
