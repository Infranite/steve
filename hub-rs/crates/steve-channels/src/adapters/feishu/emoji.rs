/// `inner` (the text between the brackets) is one of Feishu's emoji names.
pub fn is_emoji(inner: &str) -> bool {
    EMOJI_TYPES.iter().any(|e| e.eq_ignore_ascii_case(inner)) || TEXT_NAMES.contains(&inner)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn only_the_platforms_emoji_names() {
        for e in ["OK", "Thumbsup", "FullMoonFace", "赞", "微笑", "666"] {
            assert!(is_emoji(e), "{e}");
        }
        for w in [
            "merge_forward消息",
            "todo消息",
            "TODO",
            "Yes",
            "收到",
            "123",
            "system",
        ] {
            assert!(!is_emoji(w), "{w}");
        }
    }
}
