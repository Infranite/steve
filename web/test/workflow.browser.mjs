// Vite fixture: exercises dependency display and revision-bearing actions without a live provider.
import assert from "node:assert/strict"
import { settle } from "./settle.mjs"
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || "playwright")
const browser = await chromium.launch({ headless: true, ...(process.env.PLAYWRIGHT_EXECUTABLE ? { executablePath: process.env.PLAYWRIGHT_EXECUTABLE } : {}) })
const base = process.env.STEVE_TEST_WEB || "http://127.0.0.1:5189"
const errors = []
try {
  for (const width of [1066, 390, 375, 320]) for (const theme of ["dark", "light"]) {
    const page = await browser.newPage({ locale: "zh-CN", viewport: { width, height: 950 }, colorScheme: theme })
    page.on("pageerror", (e) => errors.push(e.message))
    await page.route(/\/api\/[^/]+$/, (route) => {
      if (new URL(route.request().url()).pathname.startsWith("/api/")) return route.fulfill({ json: {} })
      return route.continue()
    })
    const changes = (...keys) => page.evaluate((keys) => (window.__workflowChanges ?? []).map((c) => Object.fromEntries(keys.map((k) => [k, c[k]]))), keys)
    const narrow = width < 1024
    const select = async (key) => { await page.locator(`[data-agent-node="${key}"]`).click(); await page.locator(`[data-agent-detail="${key}"]`).waitFor() }
    const closeDetail = async () => { await page.locator("[data-agent-detail-close]").click(); await page.locator("[data-agent-panel]").waitFor({ state: "detached" }) }
    await page.goto(base + "/test/fixtures/workflow.html")
    await page.locator("[data-agent-tree]").waitFor()
    assert.deepEqual(await page.locator('[data-agent-node^="unit:"]').evaluateAll((els) => els.map((e) => e.dataset.agentNode)), ["unit:api", "unit:web", "unit:review", "unit:integrate"], "units follow dependencies")
    assert.equal(await page.locator('[data-agent-node="unit:api"] [data-agent-bar="done"]').count(), 1, "a step that ran has a bar on the time axis")
    assert.match(await page.locator("[data-agent-count]").innerText(), /5 个 agent/)
    await page.locator("[data-agent-total]").waitFor()
    assert.match(await page.locator("[data-agent-total]").innerText(), /估 \$0\.94/, "the coordinator's total holds everything started from it")
    assert.match(await page.locator('[data-agent-node="unit:api"]').innerText(), /45 秒/)
    assert.match(await page.locator('[data-agent-node="unit:api"] [data-agent-bar]').getAttribute("title"), /\$0\.29/, "a bar tells its cost")
    assert.match(await page.locator('[data-agent-node="unit:integrate"]').innerText(), /等待：独立复核依赖门控与恢复/)
    assert.match(await page.locator("[data-workflow-decisions]").innerText(), /1 张卡等你/)
    await page.locator("[data-workflow-blockers] summary").click()
    // the details open with a height animation (visual system v2); read them once it has finished
    await settle(page)
    assert.match(await page.locator("[data-workflow-blockers]").innerText(), /为什么还不能完成.*独立复核依赖门控与恢复尚未通过/s)
    await page.locator("[data-agent-failed]").click()
    assert.match(await page.locator("[data-agent-failed-list]").innerText(), /独立复核依赖门控与恢复.*刷新恢复后需要补充验证/s)
    await page.keyboard.press("Escape")
    await select("unit:api")
    assert.match(await page.locator("[data-workflow-outputs]").innerText(), /正式成果.*工作图 API.*过程记录.*构建记录/s)
    assert.match(await page.locator("[data-agent-panel]").innerText(), /实际操作/)
    if (process.env.STEVE_TEST_SHOTS) await page.screenshot({ path: `${process.env.STEVE_TEST_SHOTS}/agent-tree-${width}-${theme}.png`, fullPage: true })
    await page.locator('[data-workflow-rework="api"]').click()
    await page.getByRole("alertdialog", { name: "返工影响预览" }).waitFor()
    assert.match(await page.getByRole("alertdialog", { name: "返工影响预览" }).innerText(), /独立复核依赖门控与恢复/, "rework previews downstream review")
    assert.deepEqual(await changes(), [], "preview does not mutate the workflow")
    await page.getByRole("alertdialog", { name: "返工影响预览" }).locator('[data-slot="alert-dialog-cancel"]').click()
    if (!narrow) {
      await page.locator('[data-agent-node="unit:web"]').click()
      await page.locator('[data-agent-detail="unit:web"]').waitFor()
      assert.match(await page.locator("[data-agent-panel]").innerText(), /缺少当前回合的新鲜执行证据/, "another card can be picked while the panel is open")
    }
    await closeDetail()
    await page.locator("[data-workflow-toggle]").click()
    await page.getByText("编排已暂停，恢复后按当前计划继续。").waitFor()
    await page.locator("[data-workflow-toggle]").click()
    await page.getByRole("button", { name: "暂停编排" }).waitFor()
    await select("unit:review")
    await page.locator('[data-agent-panel] [data-workflow-retry="review"]').click()
    assert.deepEqual(await changes("action", "expected_revision"), [
      { action: "pause", expected_revision: 7 }, { action: "resume", expected_revision: 8 }, { action: "retry", expected_revision: 9 },
    ])
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false)
    await page.goto(base + "/test/fixtures/workflow.html?prior")
    await page.locator("[data-workflow-prior-cycle]").waitFor()
    await select("unit:web")
    assert.equal(await page.locator('[data-workflow-cancel="web"]').isDisabled(), true, "old-cycle work cannot be stopped from the current page")
    await page.goto(base + "/test/fixtures/workflow.html?archive")
    await page.locator('[data-agent-node="unit:api"][data-agent-tries]').waitFor()
    assert.equal(await page.locator('[data-agent-node="ST-old"]').count(), 0, "an earlier attempt is not a step of its own")
    assert.equal(await page.locator('[data-agent-node="unit:api"]').getAttribute("data-agent-tries"), "1", "it folds into its step's row")
    assert.equal(await page.locator('[data-agent-node="unit:api"] [data-agent-bar="stopped"]').count(), 1, "as a hatched span on the same bar")
    await page.locator("[data-workflow-history] summary").click()
    await settle(page)
    assert.match(await page.locator("[data-workflow-history]").innerText(), /最近 1 条旧尝试，共 2 条/)
    await select("unit:api")
    assert.match(await page.locator("[data-agent-panel] [data-agent-tries]").innerText(), /已停止.*第 1 次尝试.*已被返工替代/s, "the step's detail lists its earlier tries")
    await page.goto(base + "/test/fixtures/workflow.html?fork")
    await page.locator('[data-agent-node="ST-64"]').waitFor()
    const order = await page.locator("[data-agent-node]").evaluateAll((els) => els.map((e) => e.dataset.agentNode))
    assert.equal(order[order.indexOf("unit:web") + 1], "ST-64", "a fork follows the row that started it")
    await page.goto(base + "/test/fixtures/workflow.html?many")
    await page.locator("[data-agent-tree]").waitFor()
    assert.ok(await page.locator('[data-agent-node^="unit:"]').count() > 4, "every step is a row")
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false)
    await page.goto(base + "/test/fixtures/workflow.html?rework")
    await select("unit:api")
    await page.locator('[data-workflow-rework="api"]').click()
    await page.locator("[data-workflow-rework-confirm]").click()
    assert.deepEqual(await changes("action", "unit_id", "expected_revision"), [{ action: "retry", unit_id: "api", expected_revision: 7 }])
    await page.goto(base + "/test/fixtures/workflow.html?reworkActive")
    await select("unit:api")
    await page.locator('[data-workflow-rework="api"]').click()
    assert.match(await page.locator("[data-workflow-rework-confirm]").innerText(), /先停止受影响工作/)
    await page.locator("[data-workflow-rework-confirm]").click()
    assert.deepEqual(await changes("action", "unit_id", "expected_revision"), [{ action: "cancel", unit_id: "review", expected_revision: 7 }])
    await page.goto(base + "/test/fixtures/workflow.html?unavailable")
    await page.locator("[data-workflow-unavailable]").waitFor()
    assert.match(await page.locator("[data-workflow-unavailable]").innerText(), /协作执行暂不可用/)
    assert.equal(await page.locator("[data-workflow-toggle]").isDisabled(), true, "resume cannot bypass unavailable execution")
    assert.equal(await page.getByText("编排已暂停，恢复后按当前计划继续。").count(), 0, "no false promise to resume")
    assert.match(await page.locator('[data-agent-node="unit:integrate"]').getAttribute("data-agent-status"), /paused|blocked/)
    await select("unit:review")
    assert.equal(await page.locator('[data-agent-panel] [data-workflow-retry="review"]').isDisabled(), true)
    await closeDetail()
    assert.deepEqual(await changes(), [])
    const single = async () => { await page.locator("[data-agent-more]").click(); await page.locator("[data-workflow-single]").click(); await page.locator("[data-workflow-single-confirm]").waitFor() }
    await single()
    assert.match(await page.locator("[data-workflow-single-confirm]").innerText(), /不会记为通过/)
    await page.locator('[data-slot="alert-dialog-cancel"]').click()
    assert.deepEqual(await changes(), [], "cancelling confirmation never changes acceptance mode")
    await single()
    assert.equal(await page.locator("[data-workflow-single-confirm]").evaluate(el => el.scrollWidth > el.clientWidth), false)
    if (process.env.STEVE_TEST_SHOTS) await page.screenshot({ path: `${process.env.STEVE_TEST_SHOTS}/workflow-single-confirm-${width}-${theme}.png`, animations: "disabled" })
    await page.locator("[data-workflow-single-ok]").click()
    await page.locator("[data-workflow-single-confirm]").waitFor({ state: "detached" })
    await page.locator("[data-workflow-single-mode]").waitFor()
    assert.match(await page.locator("[data-workflow-single-mode]").innerText(), /已取消的协作单元不视为通过/)
    assert.equal(await page.locator("[data-workflow-toggle]").count(), 0)
    assert.equal(await page.locator("[data-workflow-unavailable]").count(), 0, "Node capability is not a blocker for the explicitly chosen non-collaborative path")
    assert.equal(await page.locator("[data-workflow-blockers]").count(), 0)
    assert.equal(await page.locator('[data-agent-node="unit:review"]').getAttribute("data-agent-status"), "stopped")
    assert.equal(await page.locator('[data-agent-node="unit:api"]').getAttribute("data-agent-status"), "done", "previous evidence stays unchanged")
    assert.deepEqual(await changes("action", "expected_revision"), [{ action: "single_session", expected_revision: 7 }])
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false)
    await page.goto(base + "/test/fixtures/workflow.html?unavailable&conflict")
    await single()
    await page.locator("[data-workflow-single-ok]").click()
    await page.getByRole("alert").waitFor()
    assert.match(await page.getByRole("alert").innerText(), /重新确认/)
    assert.equal(await page.locator("[data-workflow-single-mode]").count(), 0, "conflicting confirmation must not show success")
    await page.goto(base + "/test/fixtures/workflow.html?wait&held")
    await page.locator("[data-dependency-wait]").waitFor()
    assert.match(await page.locator("[data-wait-policy]").innerText(), /尚未单独登记/)
    assert.match(await page.locator("[data-wait-blocker]").innerText(), /调度暂停/)
    assert.equal(await page.locator("[data-wait-save]").isDisabled(), true)
    await page.locator('[data-select="dependency-resume"]').click()
    await page.getByRole("option", { name: "提醒我开始" }).click()
    await page.locator("[data-wait-reason]").fill("等待隔离验收")
    await page.locator("[data-wait-save]").click()
    await page.getByText("已登记 · 前置完成后提醒开始").waitFor()
    assert.match(await page.locator("[data-wait-blocker]").innerText(), /调度暂停/, "saving a policy does not clear the scheduler hold")
    assert.deepEqual(await page.evaluate(() => window.__waitChanges), [{ expected_cycle: 11, resume: "notify", reason: "等待隔离验收" }])
    assert.deepEqual(await page.evaluate(() => window.__workflowChanges ?? []), [])
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false)
    await page.goto(base + "/test/fixtures/workflow.html?wait&stale")
    await page.locator("[data-wait-reason]").fill("旧页面")
    await page.locator("[data-wait-save]").click()
    await page.getByRole("alert").waitFor()
    assert.match(await page.getByRole("alert").innerText(), /刷新/)
    assert.match(await page.locator("[data-wait-policy]").innerText(), /尚未单独登记/, "a conflict must not display a saved policy")
    await page.goto(base + "/test/fixtures/workflow.html?graph")
    await page.locator('[data-graph-mode="blocking"]').waitFor()
    assert.equal(await page.locator('[data-graph-list-node="missing:ST-missing"]').count(), 1, "missing dependencies stay visible")
    if (width < 640) {
      await page.locator('[data-graph-list-node="work:ST-60:api"]').click()
      assert.match(await page.locator("[data-graph-detail]").innerText(), /实现接口与主体检查/)
      await page.locator("[data-graph-detail] button").click()
      assert.equal(await page.evaluate(() => window.__graphOpened), "ST-61")
    }
    await page.getByRole("button", { name: "来源与派生" }).click()
    await page.locator('[data-graph-mode="lineage"]').waitFor()
    assert.equal(await page.locator('[data-graph-list-node="session-old"]').count(), 1, "source session is retained")
    if (width < 640) { await page.locator('[data-graph-list-node="ST-61"]').click(); assert.match(await page.locator("[data-graph-detail]").innerText(), /来源位置 23/) }
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false)
    if (process.env.STEVE_TEST_SHOTS) await page.screenshot({ path: `${process.env.STEVE_TEST_SHOTS}/workflow-${width}-${theme}.png`, fullPage: true })
    await page.close()
  }
  assert.deepEqual(errors, [])
  console.log(JSON.stringify({ passed: true, scenarios: ["steps in dependency order on one time axis", "cost and time figures", "failed and waiting pills", "acceptance blockers", "detail panel and shared outputs", "pause/resume/retry revisions", "attempts folded into their step, forks after their row", "rework preview, reset and stop first", "prior-cycle isolation and archived attempts", "unavailable execution disables resume and retry", "explicit single-session confirmation, cancellation and conflict", "persisted wait policy and scheduling hold", "cycle conflict keeps unsaved state", "blocking/provenance graph and mobile list", "1066/390/375/320px", "dark/light"] }))
} finally { await browser.close() }
