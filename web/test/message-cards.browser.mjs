import assert from "node:assert/strict"
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || "playwright")
const browser = await chromium.launch({ headless: true, ...(process.env.PLAYWRIGHT_EXECUTABLE ? { executablePath: process.env.PLAYWRIGHT_EXECUTABLE } : {}) })
const base = process.env.STEVE_TEST_WEB || "http://127.0.0.1:5193"
const page = await browser.newPage({ locale: "zh-CN", viewport: { width: 390, height: 844 } })
const errors = [], external = []
page.on("pageerror", e => errors.push(e.message))
page.on("console", m => { if (m.type() === "error" && m.text().includes("Base UI:")) errors.push(m.text()) })
await page.route("**/*", route => { const u = new URL(route.request().url()); if (u.origin !== base) { external.push(u.href); return route.abort() }; return route.continue() })
try {
  await page.goto(base + "/test/fixtures/message-cards.html")
  await page.locator('[data-message-card="1"]').waitFor()
  await page.locator('[data-message-card="2"]').waitFor()
  await page.locator('[data-streamdown="strong"]').filter({ hasText: "版本 1.0 卡片" }).waitFor()
  assert.equal(await page.getByText("卡片文本回退", { exact: true }).count(), 0)
  assert.equal(await page.getByRole("link", { name: "查看说明" }).getAttribute("href"), "https://example.com/release")
  assert.equal(await page.getByRole("button", { name: /批准发布/ }).count(), 0)
  assert.equal(await page.getByRole("link", { name: /已停用操作|恶意操作/ }).count(), 0)
  await page.getByText("卡片内图片请在飞书中查看", { exact: true }).waitFor()
  await page.getByText("文件夹请在飞书中打开", { exact: true }).waitFor()
  assert.equal(await page.locator('img[src^="http"]').count(), 0)
  assert.equal(await page.locator('[data-card-table] tr').count(), 3)
  assert.equal(await page.getByText("折叠区正文", { exact: true }).isVisible(), false)
  await page.getByText("详细信息", { exact: true }).click()
  await page.getByText("折叠区正文", { exact: true }).waitFor()
  await page.getByText("新组件保留的文字", { exact: true }).waitFor()
  await page.locator('[data-card-truncated]').waitFor()
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, "cards must not expand mobile viewport")
  if (process.env.STEVE_TEST_ARTIFACTS) await page.screenshot({ path: process.env.STEVE_TEST_ARTIFACTS + "/cards-mobile.png", fullPage: true })
  await page.setViewportSize({ width: 1280, height: 900 })
  const columns = await page.locator('[data-card-columns]').evaluate(el => [...el.children].map(e => e.getBoundingClientRect().y))
  assert.equal(columns[0], columns[1], "columns must align horizontally on desktop")
  if (process.env.STEVE_TEST_ARTIFACTS) await page.screenshot({ path: process.env.STEVE_TEST_ARTIFACTS + "/cards-desktop.png", fullPage: true })
  await page.evaluate(() => window.dispatchEvent(new Event("fixture-purge")))
  await page.locator('[data-message-purged]').waitFor()
  assert.equal(await page.getByText("发布评审", { exact: true }).count(), 0)
  await page.evaluate(() => window.dispatchEvent(new Event("fixture-recall")))
  await page.getByText("消息已撤回", { exact: true }).waitFor()
  assert.equal(await page.getByText("项目进展", { exact: true }).count(), 0)
  assert.deepEqual(external, []); assert.deepEqual(errors, [])
  console.log(JSON.stringify({ passed: true, scenarios: ["schema 1", "schema 2", "markdown", "no duplicated text", "safe URL action", "callback readonly", "disabled action", "bad scheme", "card image fallback", "folder fallback", "URL binding", "table", "panel", "unknown fallback", "truncated notice", "390px layout", "desktop columns", "purged hides media", "recalled hides media"] }))
} finally { await browser.close() }
