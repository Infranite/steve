"use client"

import * as React from "react"
import { Command as CommandPrimitive } from "cmdk"
import { cn } from "cn"

import {
  Dialog,
  DialogContent,
  DialogDescription,
  DialogHeader,
  DialogTitle,
} from "@/components/ui/dialog"
import {
  InputGroup,
  InputGroupAddon,
} from "@/components/ui/input-group"
import { SearchIcon, CheckIcon } from "lucide-react"

function Command({
  className,
  ...props
}: React.ComponentProps<typeof CommandPrimitive>) {
  return (
    <CommandPrimitive
      data-slot="command"
      className={cn(
        "flex size-full flex-col overflow-hidden rounded-xl bg-popover p-1 text-popover-foreground",
        className
      )}
      {...props}
    />
  )
}

function CommandDialog({
  title = "Command Palette",
  description = "Search for a command to run...",
  children,
  className,
  showCloseButton = false,
  ...props
}: Omit<React.ComponentProps<typeof Dialog>, "children"> & {
  title?: string
  description?: string
  className?: string
  showCloseButton?: boolean
  children: React.ReactNode
}) {
  return (
    <Dialog {...props}>
      <DialogHeader className="sr-only">
        <DialogTitle>{title}</DialogTitle>
        <DialogDescription>{description}</DialogDescription>
      </DialogHeader>
      <DialogContent
        className={cn(
          "top-1/3 translate-y-0 overflow-hidden rounded-2xl! p-0",
          className
        )}
        showCloseButton={showCloseButton}
      >
        {children}
      </DialogContent>
    </Dialog>
  )
}

/** `header`: the query as the head of a palette (⌘K) — borderless and taller, one hairline under it — instead of a
 *  filled field inside the box */
function CommandInput({
  className,
  header = false,
  ...props
}: React.ComponentProps<typeof CommandPrimitive.Input> & { header?: boolean }) {
  return (
    <div data-slot="command-input-wrapper" className={header ? "border-b border-border/70 p-1.5" : "p-1 pb-0"}>
      <InputGroup className={header ? "h-11! border-0! bg-transparent! ring-0! shadow-none" : "h-8! bg-input/50"}>
        <CommandPrimitive.Input
          data-slot="command-input"
          className={cn(
            "w-full outline-hidden disabled:cursor-not-allowed disabled:opacity-50",
            header ? "type-body" : "type-callout",
            className
          )}
          {...props}
        />
        <InputGroupAddon>
          <SearchIcon className="size-4 shrink-0 opacity-50" />
        </InputGroupAddon>
      </InputGroup>
    </div>
  )
}

