import AppKit
import SteveClientKit
import SwiftUI

/// One restoration path for the Dock, pairing, menu-bar actions and navigation commands.
/// The Window scene is single-instance; openWindow cannot create a competing WebView.
@MainActor
enum MacMainWindow {
    static let sceneID = "main"
    private static var sceneOpener: (() -> Void)?
    private static var restorationPending = false

    static var windows: [NSWindow] {
        NSApplication.shared.windows.filter {
            $0.identifier?.rawValue == sceneID && !$0.isSheet
        }
    }

    static func installOpener(_ open: @escaping () -> Void) {
        sceneOpener = open
        if restorationPending {
            restorationPending = false
            bringUpMainWindow()
        }
    }

    static func bringUpMainWindow(open: (() -> Void)? = nil) {
        if let window = windows.first(where: { $0.isVisible || $0.isMiniaturized }) {
            if window.isMiniaturized { window.deminiaturize(nil) }
            window.makeKeyAndOrderFront(nil)
        } else if let open = open ?? sceneOpener {
            open()
        } else {
            // A cold-start URL can arrive before SwiftUI installs the menu-bar item's opener.
            restorationPending = true
        }
        NSApplication.shared.activate(ignoringOtherApps: true)
    }

    static func navigate(_ route: String, coordinator: SteveClientCoordinator, open: (() -> Void)? = nil) {
        // Queue before restoring: a new WebView must wait for its own ready/ack handshake.
        coordinator.navigate(hashRoute: route)
        bringUpMainWindow(open: open)
    }
}

@MainActor
final class MacApplicationDelegate: NSObject, NSApplicationDelegate {
    weak var attention: MacAttentionController?
    weak var coordinator: SteveClientCoordinator? {
        didSet {
            guard coordinator != nil, !pendingURLs.isEmpty else { return }
            let urls = pendingURLs
            pendingURLs.removeAll()
            application(NSApplication.shared, open: urls)
        }
    }
    private var pendingURLs: [URL] = []

    func applicationShouldTerminateAfterLastWindowClosed(_ sender: NSApplication) -> Bool { false }

    func applicationShouldHandleReopen(_ sender: NSApplication, hasVisibleWindows flag: Bool) -> Bool {
        MacMainWindow.bringUpMainWindow()
        return false
    }

    // A single Window does not use WindowGroup's external-event scene selection. AppKit is
    // the sole URL consumer, including on cold launch, so one link stages one confirmation.
    func application(_ application: NSApplication, open urls: [URL]) {
        guard let coordinator else { pendingURLs.append(contentsOf: urls); return }
        for url in urls where url.scheme?.lowercased() == "steve" {
            coordinator.requestExternalPairingConfirmation(uri: url.absoluteString)
            MacMainWindow.bringUpMainWindow()
        }
    }

    func applicationDidBecomeActive(_ notification: Notification) {
        coordinator?.handleAppDidBecomeActive()
    }

    func applicationWillTerminate(_ notification: Notification) {
        // Stops only the client's polling/proxy; this never stops a local or remote Hub.
        attention?.stop()
        coordinator?.stop()
    }
}

/// Lives on the persistent menu-bar label, not on a main window that can be closed.
struct MacMainWindowLifecycle: ViewModifier {
    @ObservedObject var coordinator: SteveClientCoordinator
    @Environment(\.openWindow) private var openWindow

    func body(content: Content) -> some View {
        content
            .onAppear {
                MacMainWindow.installOpener { openWindow(id: MacMainWindow.sceneID) }
                if coordinator.pendingExternalPairConfirmation != nil {
                    MacMainWindow.bringUpMainWindow()
                }
            }
            .onChange(of: coordinator.pendingExternalPairConfirmation?.id) { _, pendingID in
                guard pendingID != nil else { return }
                MacMainWindow.bringUpMainWindow()
            }
    }
}

/// Give AppKit restoration and the debug harness an explicit identifier rather than relying
/// on undocumented identifiers generated by SwiftUI for a scene.
struct MacMainWindowIdentifier: NSViewRepresentable {
    func makeNSView(context: Context) -> NSView { WindowMarker() }
    func updateNSView(_ nsView: NSView, context: Context) {}

    private final class WindowMarker: NSView {
        override func viewDidMoveToWindow() {
            super.viewDidMoveToWindow()
            window?.identifier = NSUserInterfaceItemIdentifier(MacMainWindow.sceneID)
        }
    }
}
